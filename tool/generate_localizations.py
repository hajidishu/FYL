"""Generate FYL's synchronous Flutter catalogs from editable UTF-8 JSON files.

This script only reads and writes source files; it does not launch Flutter.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = ('zh-Hans', 'zh-Hant', 'en', 'ru', 'fr', 'de')


def generate(check=False):
    catalogs = {}
    for language in LANGUAGES:
        path = ROOT / 'lib/l10n/catalogs' / (language + '.json')
        catalogs[language] = json.loads(path.read_text(encoding='utf-8'))
    source = catalogs['zh-Hans']
    for language, messages in catalogs.items():
        if messages.keys() != source.keys():
            missing = source.keys() - messages.keys()
            extra = messages.keys() - source.keys()
            raise ValueError(f'{language}: missing={sorted(missing)}, extra={sorted(extra)}')
        for key, value in messages.items():
            if not isinstance(value, str) or not value:
                raise ValueError(f'{language}: empty message {key!r}')
            if set(re.findall(r'\{p\d+\}', value)) != set(re.findall(r'\{p\d+\}', source[key])):
                raise ValueError(f'{language}: placeholders differ in {key!r}')
    arguments = json.loads((ROOT / 'lib/l10n/message_arguments.json').read_text(encoding='utf-8'))
    for key, positions in arguments.items():
        if key not in source or not set(positions) <= {int(value) for value in re.findall(r'\{p(\d+)\}', key)}:
            raise ValueError(f'Invalid translatable argument positions: {key}')
    digest = hashlib.sha256(json.dumps([catalogs, arguments], ensure_ascii=False, sort_keys=True).encode()).hexdigest()
    output = ROOT / 'lib/l10n/translations.g.dart'
    if check:
        if f'// Catalog SHA-256: {digest}' not in output.read_text(encoding='utf-8'):
            raise ValueError('Compiled translations are stale. Regenerate translations.g.dart.')
        print(f'Validated {len(source)} messages for {len(catalogs)} languages.')
        return

    def quote(value):
        return json.dumps(value, ensure_ascii=False).replace('$', r'\$')
    lines = ['// Generated by tool/generate_localizations.py. Do not edit.',
             '// Edit lib/l10n/catalogs/*.json, then rerun the generator.',
             f'// Catalog SHA-256: {digest}',
             'const translationCatalogs = <String, Map<String, String>>{']
    for language, messages in catalogs.items():
        lines.append(f'  {quote(language)}: {{')
        lines += [f'    {quote(key)}: {quote(value)},' for key, value in messages.items()]
        lines.append('  },')
    lines.append('};\n')
    lines.append('const translatedArguments = <String, List<int>>{')
    for key, positions in arguments.items():
        if key in source and positions:
            lines.append(f'  {quote(key)}: {positions},')
    lines.append('};\n')
    output.write_text('\n'.join(lines), encoding='utf-8')
    print(f'Generated {len(source)} messages for {len(catalogs)} languages.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Validate catalogs and generated-source freshness without writing files.')
    generate(parser.parse_args().check)
